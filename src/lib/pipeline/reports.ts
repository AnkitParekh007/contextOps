export function buildMarkdown(input:{
  organization:string;workspace:string;date:string;sampleSize:number;taskVolume:number;
  baselineCost:number;candidateCost:number;simulatedSavings:number;quality:number|null;
  eligible:number;escalated:number;blocked:number;model:string;policy:string;assumptions:string[];
  categories:string[];auditTrail:string[];
}):string {
  const safe=(str:string)=>str.replace(/[\r\n|<>]/g," ").slice(0,150);
  const money=(num:number)=>"$"+num.toFixed(2);
  return [
    "# ContextOps AI — Cost & Quality Assessment",
    "",
    "**Organization:** "+safe(input.organization),
    "**Workflow:** "+safe(input.workspace),
    "**Generated:** "+input.date,
    "**Evidence level:** SIMULATION ONLY — no verified realized savings",
    "",
    "## Executive summary",
    "",
    "This report evaluates a hypothetical routing policy over a representative sample. ",
    "It does not establish actual savings, operational acceptance, or parity with a premium model.",
    "",
    "## Data sample and baseline",
    "",
    "- Traces analyzed: "+input.sampleSize,
    "- Monthly volume assumption: "+input.taskVolume,
    "- Baseline sample model cost: "+money(input.baselineCost),
    "- Candidate + fallback sample cost: "+money(input.candidateCost),
    "- Simulated sample savings: "+money(input.simulatedSavings),
    "- Verified savings: NOT AVAILABLE",
    "",
    "## Task categories identified",
    "",
    ...(input.categories.length?input.categories.map(s=>"- "+safe(s)):["- Not available"]),
    "",
    "## Routing and quality",
    "",
    "- Candidate model: "+safe(input.model),
    "- Routing policy: "+safe(input.policy),
    "- Eligible for cheaper routing: "+input.eligible,
    "- Premium fallback/escalation: "+input.escalated,
    "- Blocked / human review: "+input.blocked,
    "- Measured test-set quality: "+(input.quality===null?"Not evaluated":(input.quality*100).toFixed(1)+"%"),
    "",
    "## Assumptions",
    "",
    ...input.assumptions.map(s=>"- "+safe(s)),
    "",
    "## Risks and limitations",
    "",
    "- Shadow mode is offline and did not replace any production provider response.",
    "- Candidate model quality on test cases does not guarantee performance on new cases.",
    "- Pricing excludes provider discounts, caching and data transfer unless explicitly modeled.",
    "- Sensitive or unsupported tasks require escalation and human approval.",
    "- Customer security, legal and provider processing approvals are required for real-data pilots.",
    "",
    "## Audit trail (recent workflow events)",
    "",
    ...(input.auditTrail.length?input.auditTrail.map(s=>"- "+safe(s)):["- No prior audit events"]),
    "",
    "## Recommended next steps",
    "",
    "Run a representative, consented shadow evaluation with human-reviewed labels; ",
    "recalculate net costs including provider retries and platform fees; review the audit trail.",
    "",
    "_Generated by ContextOps AI. All estimates are subject to verification._",
  ].join("\n");
}
